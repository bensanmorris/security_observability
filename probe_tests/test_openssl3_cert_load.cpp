static bool test_use_certificate_asn1()
{
    std::cout << "[3] SSL_CTX_use_certificate_ASN1 (embedded DER)\n"
              << "    CN=valid.example.com (compile-time embedded, no file I/O)\n";

    SSL_CTX* ctx = make_ctx();
    if (!ctx) return false;

    int rc = SSL_CTX_use_certificate_ASN1(ctx, kEmbeddedCertDERLen, kEmbeddedCertDER);
    SSL_CTX_free(ctx);

    if (rc != 1) {
        std::cerr << "  FAIL (rc=" << rc << ")\n";
        print_ssl_errors("SSL_CTX_use_certificate_ASN1");
        return false;
    }
    std::cout << "    PASS\n";
    return true;
}

// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------
static void usage(const char* prog)
{
    std::cerr << "Usage: " << prog << " [--pause] [--test 1|2|3] [cert.pem]\n"
              << "\n"
              << "  --test N   Run only test N (1, 2, or 3). Default: run all.\n"
              << "  --pause    After tests complete, pause until Ctrl+C.\n"
              << "  cert.pem   Certificate for tests 1 & 2 (default: ../test-certs/valid.crt).\n"
              << "             Test 3 always uses its compile-time embedded cert.\n";
}

int main(int argc, char* argv[])
{
    bool do_pause = false;
    int  only_test = 0;   // 0 = run all
    int  cert_arg  = 1;

    for (int i = 1; i < argc; ++i) {
        std::string arg = argv[i];
        if (arg == "--pause") {
            do_pause = true;
        } else if (arg == "--test") {
            if (i + 1 >= argc) {
                std::cerr << "Error: --test requires an argument (1, 2, or 3)\n";
                usage(argv[0]);
                return 1;
            }
            only_test = std::stoi(argv[++i]);
            if (only_test < 1 || only_test > 3) {
                std::cerr << "Error: --test argument must be 1, 2, or 3\n";
                usage(argv[0]);
                return 1;
            }
        } else if (arg == "--help" || arg == "-h") {
            usage(argv[0]);
            return 0;
        } else {
            cert_arg = i;
        }
    }

    const std::string cert_path = (cert_arg < argc && std::string(argv[cert_arg]) != "--pause"
                                   && std::string(argv[cert_arg]).rfind("--", 0) != 0)
                                  ? argv[cert_arg]
                                  : "../test-certs/valid.crt";

    OPENSSL_init_ssl(
        OPENSSL_INIT_LOAD_SSL_STRINGS | OPENSSL_INIT_LOAD_CRYPTO_STRINGS,
        nullptr);

    std::cout << "=== openssl3-cert-load uprobe probe test ===\n"
              << "cert: " << cert_path << "\n\n";

    int run = 0, failures = 0;

    if (only_test == 0 || only_test == 1) {
        if (!test_use_certificate_file(cert_path)) ++failures;
        ++run;
        std::cout << "\n";
    }
    if (only_test == 0 || only_test == 2) {
        if (!test_use_certificate_chain_file(cert_path)) ++failures;
        ++run;
        std::cout << "\n";
    }
    if (only_test == 0 || only_test == 3) {
        if (!test_use_certificate_asn1()) ++failures;
        ++run;
    }

    std::cout << "\n=== " << (run - failures) << "/" << run << " passed";
    if (failures)
        std::cout << " (" << failures << " failed)";
    std::cout << " ===\n";

    if (do_pause) {
        std::cout << "PID " << getpid() << " pausing — press Ctrl+C to exit\n";
        pause();
    }

    return failures ? 1 : 0;
}
